import { execFileSync } from 'node:child_process';
import { appendFile, mkdir, mkdtemp, readFile, stat } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

const archive = path.resolve('dist/npm-tool/npm.tgz');
const options = { encoding: 'utf8', windowsHide: true };

async function checkNpm(root, expected) {
  const manifest = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
  if (manifest.name !== 'npm' || manifest.version !== expected) {
    throw new Error(`Expected npm ${expected} at ${root}, found ${manifest.name} ${manifest.version}`);
  }
  const cli = path.join(root, 'bin', 'npm-cli.js');
  if (!(await stat(cli)).isFile()) throw new Error(`Not a file: ${cli}`);
  const actual = execFileSync(process.execPath, [cli, '--version'], options).trim();
  if (actual !== expected) throw new Error(`Expected npm ${expected} from ${cli}, got ${actual}`);
  return cli;
}

async function main([mode, expected]) {
  if (!expected || !['stage', 'use'].includes(mode)) throw new Error('Usage: npm-tool.mjs stage|use VERSION');
  if (mode === 'stage') {
    // The Linux pack step also uses npm from PATH. Only archive that global
    // package, not its prefix or user config. Installed .bin links are POSIX
    // shims generated by the global install, not part of npm's JS package.
    const root = path.join(execFileSync('npm', ['root', '--global'], options).trim(), 'npm');
    await checkNpm(root, expected);
    await mkdir(path.dirname(archive), { recursive: true });
    execFileSync('tar', ['--exclude=./node_modules/.bin', '--exclude=./.npmrc', '--exclude=./npmrc',
      '-czf', archive, '-C', root, '.'], options);
  } else {
    const envFile = process.env.GITHUB_ENV;
    if (!envFile) throw new Error('GITHUB_ENV is required');
    // A fresh, short path avoids stale files and long paths on Windows.
    const root = await mkdtemp(path.join(os.tmpdir(), 'npm-'));
    execFileSync('tar', ['-xzf', archive, '-C', root], options);
    const cli = await checkNpm(root, expected);
    await appendFile(envFile, `npm_execpath=${cli}\n`);
    console.log(`Using staged npm ${expected}`);
  }
}

await main(process.argv.slice(2)).catch(error => { console.error(error.message); process.exitCode = 1; });
